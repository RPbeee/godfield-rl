"""Generate all five complete MAGIC_FREE artifacts, or verify them with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 5
ids = [47,153,172,180,239]
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == ids
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 6
assert manifest['stable_local_slots'] == {str(id):index for index,id in enumerate(ids)}
assert len(manifest['previous_catalog_sha256']) == 22
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(ids), 'catalog ID collision'
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable'])
expected = {47:('WEAPON','ATK','',12,20,1),153:('PROTECTOR','','DFS',6,20,1),
            172:('PROTECTOR','','DFS',9,20,1),180:('PROTECTOR','','DFS',12,20,1),
            239:('SUNDRY','','',0,5,2)}
for row in source_rows:
    id = int(row['id'])
    type, attack_kind, defense_kind, value, price, weight = expected[id]
    assert (row['type'],row['attack_kind'],row['attack_extra'],row['defense_kind']) == (type,attack_kind,'MAGIC_FREE',defense_kind)
    for field in ('defense_extra','attribute','sub_value','hit_rate'):
        assert row[field] == ''
    assert (row['value'],row['price'],row['weight']) == (str(value) if value else '',str(price),str(weight))
    kind = {'WEAPON':'weapon','PROTECTOR':'armor','SUNDRY':'sundry'}[type]
    writer.writerow([id, f'legacy-{id:03}', kind,'neutral',value if kind=='weapon' else 0,0,
                     value if kind=='armor' else 0,0,0,price,weight,int(kind!='weapon')])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
lines = [
    '// Generated by data/legacy-magic-free-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-magic-free-v1/manifest.json.',
    '#include "godfield/magic_free.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<MagicFreeCard, magic_free_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    discard = 'true' if row['discardable']=='1' else 'false'
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {discard}}}, Element::{row["element"]}}},')
lines += [
    '}};',
    'static_assert(static_cast<int>(Kind::sundry) == 4);',
    'static_assert(records[0].card.id == 47 && records[0].card.attack == 12',
    '    && records[1].card.id == 153 && records[1].card.defense == 6',
    '    && records[2].card.id == 172 && records[2].card.defense == 9',
    '    && records[3].card.id == 180 && records[3].card.defense == 12',
    '    && records[4].card.id == 239 && records[4].card.kind == Kind::sundry);',
    '}',
    'std::span<const MagicFreeCard> magic_free_catalog() noexcept { return records; }',
    'int magic_free_index(CardId id) noexcept {',
    '    for (int i = 0; i < magic_free_card_count; ++i) if (records[i].card.id == id) return i;',
    '    return -1;',
    '}',
    'const MagicFreeCard* find_magic_free_card(CardId id) noexcept {',
    '    const auto index = magic_free_index(id);',
    '    return index < 0 ? nullptr : &records[index];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/magic_free.cpp'
if args.check:
    assert target.read_text() == generated, 'magic_free.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/magic_free.hpp').read_text()
    print('MAGIC_FREE verified: five complete artifacts; twenty-two older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
