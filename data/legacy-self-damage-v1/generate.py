"""Generate the positive-weight self-damage artifact, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [53]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 1
assert manifest['stable_local_slots'] == {'53': 0}
assert len(manifest['previous_catalog_sha256']) == 28
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    assert 53 not in {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}, 'catalog ID collision'
row = source_rows[0]
assert (row['id'], row['type'], row['attack_kind'], row['attack_extra']) == ('53','WEAPON','ATK','DAMAGE_TO_SELF')
for field in ('defense_kind','defense_extra','attribute','sub_value','hit_rate'):
    assert row[field] == ''
assert (row['value'], row['price'], row['weight']) == ('14','1','1')
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
writer.writerow([53,'legacy-053','weapon',14,0,0,0,0,1,1,0])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/self_damage.hpp').read_text()
generated = '// Generated by data/legacy-self-damage-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-self-damage-v1/manifest.json.\n#include "godfield/self_damage.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<SelfDamageCard, self_damage_card_count> records{{\n    {{53, "legacy-053", Kind::weapon, 14, 0, 0, 0, 0, 1, 1, false}},\n}};\nstatic_assert(records[0].card.id == 53 && records[0].card.kind == Kind::weapon\n    && records[0].card.attack == 14 && records[0].card.price == 1\n    && records[0].card.weight == 1 && !records[0].card.discardable);\n}\nstd::span<const SelfDamageCard> self_damage_catalog() noexcept { return records; }\nint self_damage_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }\nconst SelfDamageCard* find_self_damage_card(CardId id) noexcept {\n    return self_damage_index(id) < 0 ? nullptr : &records[0];\n}\n}\n'
assert manifest['catalog_sha256'] in header
assert 'struct SelfDamageCard { Card card; };' in header
target = project / 'src/self_damage.cpp'
if args.check:
    assert target.read_text() == generated, 'self_damage.cpp needs regeneration'
    print('Self damage verified: one complete artifact; twenty-eight older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
