"""Generate the native elemental allowlist, or verify it with --check.

The transcribed source rows are independently hashed; normalization and native
table generation are deterministic. No effects are stripped to admit a card.
"""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
source_bytes = (directory / "source-rows.csv").read_bytes()
catalog_bytes = (directory / "catalog.csv").read_bytes()
manifest = json.loads((directory / "manifest.json").read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest["source_rows_sha256"]
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest["catalog_sha256"]
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest["catalog_count"]
assert [int(r["id"]) for r in rows] == manifest["selection"]["ids"]
assert len({int(r["id"]) for r in rows}) == len(rows)
assert dict(Counter(r['kind'] for r in rows)) == manifest['counts_by_kind']
assert dict(Counter(r['element'] for r in rows)) == manifest['counts_by_element']
assert sum(int(r["weight"]) for r in rows) == manifest["total_selected_weight"]
assert sum(r['kind'] == 'weapon' and int(r['boost']) > 0 for r in rows) == manifest['boost_weapon_count']
assert sum(r['kind'] == 'weapon' and int(r['defense']) > 0 for r in rows) == manifest['dual_role_weapon_count']
for original in ('legacy-neutral-v1', 'legacy-miracles-v1'):
    old_ids = {int(r['id']) for r in csv.DictReader((directory.parent / original / 'catalog.csv').read_text().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'

mapping = {'FIRE':'fire', 'WATER':'water', 'TREE':'wood', 'SOIL':'stone'}
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable'])
for row in source_rows:
    assert row['type'] in ('WEAPON', 'PROTECTOR')
    assert row['attribute'] in mapping
    assert int(row['hit_rate'] or 0) == 0
    assert int(row['weight']) > 0
    assert row['attack_extra'] in ('', 'INCREASE_ATK')
    assert row['defense_extra'] == ''
    assert row['defense_kind'] in ('', 'DFS')
    weapon = row['type'] == 'WEAPON'
    assert row['attack_kind'] == ('ATK' if weapon else '')
    if not weapon:
        assert row['defense_kind'] == 'DFS'
    value = int(row['value'])
    sub_value = int(row['sub_value'] or 0)
    attack = value if weapon else 0
    boost = (value if weapon else sub_value) if row['attack_extra'] == 'INCREASE_ATK' else 0
    defense = (sub_value if weapon else value) if row['defense_kind'] == 'DFS' else 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'weapon' if weapon else 'armor',
                     mapping[row['attribute']], attack, boost, defense, 0, 0,
                     int(row['price']), int(row['weight']), int(not weapon)])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-elements-v1/generate.py.',
    '// Source-row and normalized-data hashes: data/legacy-elements-v1/manifest.json.',
    '#include "godfield/elements.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<ElementCard, element_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}}, Element::{row["element"]}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.weight <= 0 || card.attack < 0',
    '            || card.boost < 0 || card.defense < 0 || card.hp != 0 || card.mp != 0',
    '            || card.price < 0 || entry.element == Element::neutral',
    '            || card.discardable == (card.kind == Kind::weapon)) return false;',
    '        previous = card.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    f'constexpr std::array<std::uint8_t, {int(rows[-1]["id"]) + 1}> make_index() {{',
    f'    std::array<std::uint8_t, {int(rows[-1]["id"]) + 1}> index{{}};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const ElementCard> element_catalog() noexcept { return records; }',
    'const ElementCard* find_element_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/elements.cpp'
if args.check:
    assert target.read_text() == generated, 'elements.cpp needs regeneration'
    header = (project / 'include/godfield/elements.hpp').read_text()
    assert manifest['catalog_sha256'] in header, 'header fingerprint mismatch'
    print(f'Element catalog verified: {len(rows)} cards, source rows and normalized data match.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
