"""Generate HP gamble237, or verify it and frozen catalogs/prices with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source) == manifest['catalog_count'] == 1
assert [int(r['id']) for r in rows] == manifest['selection']['ids'] == [237]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight'] == 2
assert manifest['stable_local_slots'] == {'237':0}
assert len(manifest['previous_catalog_sha256']) == 32
old_ids = set()
for original, expected in manifest['previous_catalog_sha256'].items():
    raw = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(raw).hexdigest() == expected == old_manifest['catalog_sha256']
    ids = {int(r['id']) for r in csv.DictReader(raw.decode().splitlines())}
    assert 237 not in ids and not ids & old_ids, 'catalog ID collision'
    old_ids |= ids
assert len(old_ids) == 217
prices = (directory.parent / 'legacy-selling-v1/sale-prices.csv').read_bytes()
selling = json.loads((directory.parent / 'legacy-selling-v1/manifest.json').read_text())
assert hashlib.sha256(prices).hexdigest() == manifest['previous_sale_prices_sha256'] == selling['sale_prices_sha256']
price_rows = list(csv.DictReader(prices.decode().splitlines()))
assert len(price_rows) == 216 and 237 not in {int(r['id']) for r in price_rows}
assert max(int(r['price']) for r in price_rows) == 30
row = source[0]
assert (row['id'], row['type'], row['attack_kind'], row['value'], row['price'], row['weight']) == ('237','SUNDRY','INCREASE_OR_DECREASE_HP','10','1','2')
for field in ('attack_extra','defense_kind','defense_extra','attribute','sub_value','hit_rate'):
    assert row[field] == ''
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable','amount'])
writer.writerow([237,'legacy-237','sundry',0,0,0,0,0,1,2,1,10])
assert normalized.getvalue().encode() == catalog_bytes
header = (project / 'include/godfield/hp_gamble.hpp').read_text()
assert manifest['catalog_sha256'] in header
generated = '// Generated by data/legacy-hp-gamble-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-hp-gamble-v1/manifest.json.\n#include "godfield/hp_gamble.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<HPGambleCard, hp_gamble_card_count> records{{\n    {{237, "legacy-237", Kind::sundry, 0, 0, 0, 0, 0, 1, 2, true}, 10},\n}};\nstatic_assert(records[0].card.id == 237 && records[0].card.kind == Kind::sundry\n    && records[0].card.price == 1 && records[0].card.weight == 2 && records[0].amount == 10);\n}\nstd::span<const HPGambleCard> hp_gamble_catalog() noexcept { return records; }\nint hp_gamble_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }\nconst HPGambleCard* find_hp_gamble_card(CardId id) noexcept {\n    return hp_gamble_index(id) < 0 ? nullptr : &records[0];\n}\n}\n'
path = project / 'src/hp_gamble.cpp'
if args.check:
    assert path.read_text() == generated, 'hp_gamble.cpp needs regeneration'
    print('HP gamble verified: one artifact; thirty-two earlier catalogs and216 prices intact.')
else:
    path.write_text(generated)
    print(f'Generated {path}.')
