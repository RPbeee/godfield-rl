"""Generate the complete positive-weight revival artifact, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [244]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 1
assert manifest['stable_local_slots'] == {'244':0}
assert len(manifest['previous_catalog_sha256']) == 25
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert 244 not in old_ids, 'catalog ID collision'
row = source_rows[0]
assert row['id'] == '244' and row['type'] == 'SUNDRY' and row['attack_kind'] == '' and row['attack_extra'] == 'REVIVE'
for field in ('defense_kind','defense_extra','attribute','sub_value','hit_rate'):
    assert row[field] == ''
assert (row['value'], row['price'], row['weight']) == ('10','10','1')
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable','amount'])
writer.writerow([244,'legacy-244','sundry',0,0,0,0,0,10,1,1,10])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/revival.hpp').read_text()
lines = [
    '// Generated by data/legacy-revival-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-revival-v1/manifest.json.',
    '#include "godfield/revival.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<ReviveCard, revival_card_count> records{{',
    '    {{244, "legacy-244", Kind::sundry, 0, 0, 0, 0, 0, 10, 1, true}, 10},',
    '}};',
    'static_assert(records[0].card.id == 244 && records[0].card.kind == Kind::sundry',
    '    && records[0].card.price == 10 && records[0].card.weight == 1 && records[0].amount == 10);',
    '}',
    'std::span<const ReviveCard> revival_catalog() noexcept { return records; }',
    'int revival_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }',
    'const ReviveCard* find_revival_card(CardId id) noexcept {',
    '    return revival_index(id) < 0 ? nullptr : &records[0];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/revival.cpp'
if args.check:
    assert target.read_text() == generated, 'revival.cpp needs regeneration'
    assert manifest['catalog_sha256'] in header
    print('Revival verified: one complete passive artifact; twenty-five older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
