"""Generate all physical MAGIC bounce artifacts, or verify with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
ids = [21,119,121,127,134,140]
assert len(rows) == len(source) == manifest['catalog_count'] == 6
assert [int(r['id']) for r in rows] == manifest['selection']['ids'] == ids
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight'] == 6
assert manifest['stable_local_slots'] == {str(id):i for i,id in enumerate(ids)}
assert len(manifest['previous_catalog_sha256']) == 33
old_ids = set()
for original, expected in manifest['previous_catalog_sha256'].items():
    raw = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(raw).hexdigest() == expected == old_manifest['catalog_sha256']
    seen = {int(r['id']) for r in csv.DictReader(raw.decode().splitlines())}
    assert not set(ids) & seen and not seen & old_ids, 'catalog ID collision'
    old_ids |= seen
assert len(old_ids) == 218
prices = (directory.parent / 'legacy-selling-v1/sale-prices.csv').read_bytes()
selling = json.loads((directory.parent / 'legacy-selling-v1/manifest.json').read_text())
assert hashlib.sha256(prices).hexdigest() == manifest['previous_sale_prices_sha256'] == selling['sale_prices_sha256']
assert not set(ids) & {int(r['id']) for r in csv.DictReader(prices.decode().splitlines())}
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
for i,row in enumerate(source):
    assert int(row['id']) == ids[i] and row['defense_extra'] == 'FLICK_MAGIC' and row['weight'] == '1'
    for field in ('attribute','sub_value','hit_rate'): assert row[field] == ''
    if i == 0:
        assert (row['type'],row['attack_kind'],row['attack_extra'],row['defense_kind'],row['value'],row['price']) == ('WEAPON','ATK','INCREASE_ATK','','5','10')
        writer.writerow([21,'legacy-021','weapon',5,5,0,0,0,10,1,0])
    else:
        assert (row['type'],row['attack_kind'],row['attack_extra'],row['defense_kind'],row['value'],row['price']) == ('PROTECTOR','','','DFS',str(i-1),'5')
        writer.writerow([ids[i],f'legacy-{ids[i]}','armor',0,0,i-1,0,0,5,1,1])
assert normalized.getvalue().encode() == catalog_bytes
header = (project / 'include/godfield/magic_bounce.hpp').read_text()
assert manifest['catalog_sha256'] in header
generated = '// Generated by data/legacy-magic-bounce-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-magic-bounce-v1/manifest.json.\n#include "godfield/magic_bounce.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<MagicBounceCard, magic_bounce_card_count> records{{\n    {{21, "legacy-021", Kind::weapon, 5, 5, 0, 0, 0, 10, 1, false}},\n    {{119, "legacy-119", Kind::armor, 0, 0, 0, 0, 0, 5, 1, true}},\n    {{121, "legacy-121", Kind::armor, 0, 0, 1, 0, 0, 5, 1, true}},\n    {{127, "legacy-127", Kind::armor, 0, 0, 2, 0, 0, 5, 1, true}},\n    {{134, "legacy-134", Kind::armor, 0, 0, 3, 0, 0, 5, 1, true}},\n    {{140, "legacy-140", Kind::armor, 0, 0, 4, 0, 0, 5, 1, true}},\n}};\nconstexpr auto make_index() {\n    std::array<std::uint8_t, 141> index{};\n    for (std::size_t i = 0; i < records.size(); ++i) index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);\n    return index;\n}\nconstexpr auto index = make_index();\nstatic_assert(records[0].card.id == 21 && records[0].card.attack == 5 && records[0].card.boost == 5);\nstatic_assert(records[1].card.id == 119 && records[1].card.defense == 0 && records[5].card.defense == 4);\n}\nstd::span<const MagicBounceCard> magic_bounce_catalog() noexcept { return records; }\nint magic_bounce_index(CardId id) noexcept {\n    return id < index.size() && index[id] ? static_cast<int>(index[id]) - 1 : -1;\n}\nconst MagicBounceCard* find_magic_bounce_card(CardId id) noexcept {\n    const int slot = magic_bounce_index(id);\n    return slot < 0 ? nullptr : &records[slot];\n}\n}\n'
path = project / 'src/magic_bounce.cpp'
if args.check:
    assert path.read_text() == generated, 'magic_bounce.cpp needs regeneration'
    print('Magic bounce verified: six artifacts; thirty-three older catalogs and216 prices intact.')
else:
    path.write_text(generated)
    print(f'Generated {path}.')
