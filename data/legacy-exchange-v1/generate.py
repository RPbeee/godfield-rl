"""Generate the complete EXCHANGE artifact, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [2]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 20
assert manifest['stable_local_slots'] == {'2':0}
assert len(manifest['previous_catalog_sha256']) == 24
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert 2 not in old_ids, 'catalog ID collision'
row = source_rows[0]
assert row['id'] == '2' and row['type'] == 'TRADE' and row['attack_kind'] == 'EXCHANGE'
for field in ('attack_extra','defense_kind','defense_extra','attribute','value','sub_value','hit_rate'):
    assert row[field] == ''
assert (row['price'],row['weight']) == ('10','20')
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
writer.writerow([2,'legacy-002','trade',0,0,0,0,0,10,20,1])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
lines = [
    '// Generated by data/legacy-exchange-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-exchange-v1/manifest.json.',
    '#include "godfield/exchange.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<ExchangeCard, exchange_card_count> records{{',
    '    {{2, "legacy-002", Kind::trade, 0, 0, 0, 0, 0, 10, 20, true}},',
    '}};',
    'static_assert(static_cast<int>(Kind::trade) == 5);',
    'static_assert(records[0].card.id == 2 && records[0].card.price == 10',
    '    && records[0].card.weight == 20 && records[0].card.discardable);',
    '}',
    'std::span<const ExchangeCard> exchange_catalog() noexcept { return records; }',
    'int exchange_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }',
    'const ExchangeCard* find_exchange_card(CardId id) noexcept {',
    '    return exchange_index(id) < 0 ? nullptr : &records[0];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/exchange.cpp'
if args.check:
    assert target.read_text() == generated, 'exchange.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/exchange.hpp').read_text()
    print('Exchange verified: one complete artifact; twenty-four older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
