"""Generate the complete positive-weight forgetting artifact, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json
import re

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [241]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 3
assert manifest['stable_local_slots'] == {'241':0}
assert len(manifest['previous_catalog_sha256']) == 23
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert 241 not in old_ids, 'catalog ID collision'
row = source_rows[0]
assert row['id'] == '241' and row['type'] == 'SUNDRY' and row['attack_kind'] == 'REMOVE_ABILITIES'
for field in ('attack_extra','defense_kind','defense_extra','attribute','sub_value','hit_rate'):
    assert row[field] == ''
assert (row['value'], row['price'], row['weight']) == ('1','10','3')
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable','amount'])
writer.writerow([241,'legacy-241','sundry',0,0,0,0,0,10,3,1,1])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/forgetting.hpp').read_text()
rank = re.search(r'retained_type_ids\s*\{([^}]+)\}',header).group(1)
expected_ids = [197,198,199,200,203,204,205,206,207,209,210,214,215,216,217,218,219,220,222,223,226]
assert [int(x) for x in re.findall(r'\d+',rank)] == manifest['retained_type_ids'] == expected_ids
lines = [
    '// Generated by data/legacy-forgetting-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-forgetting-v1/manifest.json.',
    '#include "godfield/forgetting.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<ForgetCard, forgetting_card_count> records{{',
    '    {{241, "legacy-241", Kind::sundry, 0, 0, 0, 0, 0, 10, 3, true}, 1},',
    '}};',
    'static_assert(records[0].card.id == 241 && records[0].card.kind == Kind::sundry',
    '    && records[0].card.price == 10 && records[0].card.weight == 3 && records[0].amount == 1);',
    '}',
    'std::span<const ForgetCard> forgetting_catalog() noexcept { return records; }',
    'int forgetting_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }',
    'const ForgetCard* find_forgetting_card(CardId id) noexcept {',
    '    return forgetting_index(id) < 0 ? nullptr : &records[0];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/forgetting.cpp'
if args.check:
    assert target.read_text() == generated, 'forgetting.cpp needs regeneration'
    assert manifest['catalog_sha256'] in header
    print('Forgetting verified: one complete artifact; twenty-three older catalogs and21 type IDs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
