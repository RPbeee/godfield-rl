"""Generate BUY4, or verify it and all frozen catalogs/prices with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source) == manifest['catalog_count'] == 1
assert [int(r['id']) for r in rows] == manifest['selection']['ids'] == [4]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight'] == 20
assert manifest['stable_local_slots'] == {'4':0}
assert len(manifest['previous_catalog_sha256']) == 31
old_ids = set()
for original, expected in manifest['previous_catalog_sha256'].items():
    raw = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(raw).hexdigest() == expected == old_manifest['catalog_sha256']
    ids = {int(r['id']) for r in csv.DictReader(raw.decode().splitlines())}
    assert 4 not in ids and not ids & old_ids, 'catalog ID collision'
    old_ids |= ids
assert len(old_ids) == 216
prices = (directory.parent / 'legacy-selling-v1/sale-prices.csv').read_bytes()
selling = json.loads((directory.parent / 'legacy-selling-v1/manifest.json').read_text())
assert hashlib.sha256(prices).hexdigest() == manifest['previous_sale_prices_sha256'] == selling['sale_prices_sha256']
price_rows = list(csv.DictReader(prices.decode().splitlines()))
assert len(price_rows) == 216 and {int(r['id']) for r in price_rows} == old_ids
assert 4 not in old_ids and max(int(r['price']) for r in price_rows) == 30
row = source[0]
assert (row['id'], row['type'], row['attack_kind'], row['price'], row['weight']) == ('4','TRADE','BUY','5','20')
for field in ('attack_extra','defense_kind','defense_extra','attribute','value','sub_value','hit_rate'):
    assert row[field] == ''
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
writer.writerow([4,'legacy-004','trade',0,0,0,0,0,5,20,1])
assert normalized.getvalue().encode() == catalog_bytes
header = (project / 'include/godfield/buying.hpp').read_text()
assert manifest['catalog_sha256'] in header
generated = '// Generated by data/legacy-buying-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-buying-v1/manifest.json.\n#include "godfield/buying.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<BuyCard, buying_card_count> records{{\n    {{4, "legacy-004", Kind::trade, 0, 0, 0, 0, 0, 5, 20, true}},\n}};\nstatic_assert(records[0].card.id == 4 && records[0].card.kind == Kind::trade\n    && records[0].card.price == 5 && records[0].card.weight == 20 && records[0].card.discardable);\n}\nstd::span<const BuyCard> buying_catalog() noexcept { return records; }\nint buying_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }\nconst BuyCard* find_buying_card(CardId id) noexcept {\n    return buying_index(id) < 0 ? nullptr : &records[0];\n}\n}\n'
path = project / 'src/buying.cpp'
if args.check:
    assert path.read_text() == generated, 'buying.cpp needs regeneration'
    print('Buying verified: one artifact; thirty-one earlier catalogs and216 prices intact.')
else:
    path.write_text(generated)
    print(f'Generated {path}.')
