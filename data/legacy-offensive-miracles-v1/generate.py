"""Generate the standalone offensive miracle catalog, or verify with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
manifest = json.loads((directory / 'manifest.json').read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count']
assert [int(r['id']) for r in rows] == manifest['selection']['ids']
assert len({int(r['id']) for r in rows}) == len(rows)
for column,key in [('element','counts_by_element'),('harm','counts_by_harm'),('hit_rate','counts_by_hit_rate')]:
    assert dict(Counter(r[column] for r in rows)) == manifest[key]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight']
for i, row in enumerate(rows):
    assert int(row['kind_index']) == manifest['stable_kind_slots'][row['id']] == i
    assert manifest['stable_cast_slots'][row['id']] == i + manifest['legacy_cast_offset']
assert manifest['legacy_cast_offset'] + len(rows) <= 16, 'ability mask capacity exceeded'
for original in ('legacy-neutral-v1','legacy-miracles-v1','legacy-elements-v1','legacy-chance-v1',
                 'legacy-reflection-v1','legacy-disease-v1','legacy-harms-v1','legacy-celestial-v1'):
    old_ids = {int(r['id']) for r in csv.DictReader((directory.parent / original / 'catalog.csv').read_text().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'
old_utility_bytes = (directory.parent / 'legacy-miracles-v1/catalog.csv').read_bytes()
assert hashlib.sha256(old_utility_bytes).hexdigest() == '07da28e8a3c809fe634f90f94a24eb9cfb53dfbdf8d2cb7658a145a2e250eb1c'
assert manifest['preserved_legacy_slots'] == {'216':0, '220':1}

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','element','amount','cost','weight','hit_rate','harm','kind_index'])
element_map = {'':'neutral','FIRE':'fire','WATER':'water','TREE':'wood','SOIL':'stone','LIGHT':'light','DARK':'dark'}
for index,row in enumerate(source_rows):
    assert row['type'] == 'MAGIC' and row['attack_kind'] == 'ATK'
    assert row['attack_extra'] in ('','GLORY')
    assert row['defense_kind'] == row['defense_extra'] == ''
    assert row['attribute'] in element_map
    assert int(row['hit_rate'] or 0) in (0,25,50,75)
    assert int(row['value']) > 0 and int(row['sub_value']) > 0 and int(row['weight']) > 0
    harm = 'glory' if row['attack_extra'] == 'GLORY' else 'none'
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', element_map[row['attribute']],
                     int(row['value']), int(row['sub_value']), int(row['weight']),
                     int(row['hit_rate'] or 0), harm, index])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-offensive-miracles-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-offensive-miracles-v1/manifest.json.',
    '#include "godfield/offensive_miracles.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<OffensiveMiracle, offensive_miracle_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('amount','cost','weight','hit_rate'))
    lines.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, Element::{row["element"]}, {fields}, Harm::{row["harm"]}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        if (entry.id <= previous || entry.weight <= 0 || entry.amount <= 0 || entry.cost <= 0',
    '            || entry.hit_rate < 0 || entry.hit_rate > 100',
    '            || (entry.harm != Harm::none && entry.harm != Harm::glory)) return false;',
    '        previous = entry.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    f'constexpr std::array<std::uint8_t, {int(rows[-1]["id"])+1}> make_index() {{',
    f'    std::array<std::uint8_t, {int(rows[-1]["id"])+1}> index{{}};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const OffensiveMiracle> offensive_miracles() noexcept { return records; }',
    'int offensive_miracle_index(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return -1;',
    '    return index[id] - 1;',
    '}',
    'const OffensiveMiracle* find_offensive_miracle(CardId id) noexcept {',
    '    const int slot = offensive_miracle_index(id);',
    '    return slot < 0 ? nullptr : &records[slot];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/offensive_miracles.cpp'
if args.check:
    assert target.read_text() == generated, 'offensive_miracles.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/offensive_miracles.hpp').read_text()
    print(f'Offensive miracle catalog verified: {len(rows)} records, utility slots/fingerprint preserved.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
