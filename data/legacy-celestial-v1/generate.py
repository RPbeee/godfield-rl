"""Generate source-preserving light/dark records, or verify them with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
manifest = json.loads((directory / 'manifest.json').read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count']
assert [int(r['id']) for r in rows] == manifest['selection']['ids']
assert len({int(r['id']) for r in rows}) == len(rows)
for column,key in [('kind','counts_by_kind'),('element','counts_by_element'),('harm','counts_by_harm'),('hit_rate','counts_by_hit_rate')]:
    assert dict(Counter(r[column] for r in rows)) == manifest[key]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight']
assert sum(int(r['boost']) > 0 for r in rows) == manifest['boost_weapon_count']
for original in ('legacy-neutral-v1','legacy-miracles-v1','legacy-elements-v1','legacy-chance-v1',
                 'legacy-reflection-v1','legacy-disease-v1','legacy-harms-v1'):
    old_ids = {int(r['id']) for r in csv.DictReader((directory.parent / original / 'catalog.csv').read_text().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable','harm','hit_rate'])
for row in source_rows:
    assert row['type'] in ('WEAPON','PROTECTOR')
    assert row['attribute'] in ('LIGHT','DARK')
    assert row['attack_extra'] in ('','INCREASE_ATK','GLORY')
    assert row['defense_extra'] == '' and row['defense_kind'] in ('','DFS')
    rate = int(row['hit_rate'] or 0)
    assert rate in (0,25,50,75)
    assert int(row['weight']) > 0
    weapon = row['type'] == 'WEAPON'
    assert row['attack_kind'] == ('ATK' if weapon else '')
    if rate:
        assert weapon and row['attack_extra'] == ''
    if not weapon:
        assert row['defense_kind'] == 'DFS' and row['attack_extra'] == ''
    value = int(row['value'])
    boost = value if row['attack_extra'] == 'INCREASE_ATK' else 0
    harm = 'glory' if row['attack_extra'] == 'GLORY' else 'none'
    defense = (int(row['sub_value'] or 0) if weapon else value) if row['defense_kind'] == 'DFS' else 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'weapon' if weapon else 'armor',
                     row['attribute'].lower(), value if weapon else 0, boost, defense, 0, 0,
                     int(row['price']), int(row['weight']), int(not weapon), harm, rate])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-celestial-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-celestial-v1/manifest.json.',
    '#include "godfield/celestial.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<CelestialCard, celestial_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}}, Element::{row["element"]}, Harm::{row["harm"]}, {int(row["hit_rate"])}}},')
lines += [
    '}};',
    'static_assert(static_cast<int>(Element::light) == 5 && static_cast<int>(Element::dark) == 6);',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.weight <= 0 || card.attack < 0 || card.boost < 0',
    '            || card.defense < 0 || card.hp != 0 || card.mp != 0 || card.price < 0',
    '            || (entry.element != Element::light && entry.element != Element::dark)',
    '            || (entry.harm != Harm::none && entry.harm != Harm::glory)',
    '            || entry.hit_rate < 0 || entry.hit_rate > 100',
    '            || card.discardable == (card.kind == Kind::weapon)) return false;',
    '        previous = card.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    f'constexpr std::array<std::uint8_t, {int(rows[-1]["id"])+1}> make_index() {{',
    f'    std::array<std::uint8_t, {int(rows[-1]["id"])+1}> index{{}};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const CelestialCard> celestial_catalog() noexcept { return records; }',
    'const CelestialCard* find_celestial_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/celestial.cpp'
if args.check:
    assert target.read_text() == generated, 'celestial.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/celestial.hpp').read_text()
    print(f'Celestial catalog verified: {len(rows)} source records; Glory source retained.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
