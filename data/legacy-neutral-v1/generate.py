"""Generate the native allowlist from catalog.csv, or verify it with --check.

This does not fetch data or infer new supported cards. Selection and provenance
are explicitly recorded in manifest.json.
"""
from pathlib import Path
import argparse
import csv
import hashlib
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
raw = (directory / "catalog.csv").read_bytes()
manifest = json.loads((directory / "manifest.json").read_text())
assert hashlib.sha256(raw).hexdigest() == manifest["catalog_sha256"]
rows = list(csv.DictReader(raw.decode().splitlines()))
assert len(rows) == manifest["catalog_count"]
assert [int(r["id"]) for r in rows] == manifest["selection"]["ids"]
assert sum(int(r["weight"]) for r in rows) == manifest["total_selected_weight"]
assert len(rows) < 256
assert len({int(r["id"]) for r in rows}) == len(rows)

source = [
    '// Generated by data/legacy-neutral-v1/generate.py. Do not edit the rows by hand.',
    '// Source facts, selection and retrieval limits: data/legacy-neutral-v1/manifest.json.',
    '#include "godfield/catalog.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    f'constexpr std::array<Card, {len(rows)}> cards{{{{',
]
for row in rows:
    assert row['kind'] in ('weapon', 'armor', 'heal', 'mana')
    fields = ', '.join(str(int(row[f])) for f in ('attack','boost','defense','hp','mp','price','weight'))
    source.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}},')
source.extend([
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& card : cards) {',
    '        if (card.id <= previous || card.weight <= 0 || card.attack < 0',
    '            || card.boost < 0 || card.defense < 0 || card.hp < 0 || card.mp < 0',
    '            || card.price < 0 || card.discardable == (card.kind == Kind::weapon)) return false;',
    '        previous = card.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    f'constexpr std::array<std::uint8_t, {int(rows[-1]["id"]) + 1}> make_index() {{',
    f'    std::array<std::uint8_t, {int(rows[-1]["id"]) + 1}> index{{}};',
    '    for (std::size_t i = 0; i < cards.size(); ++i)',
    '        index[cards[i].id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const Card> catalog() noexcept { return cards; }',
    'const Card* find_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &cards[index[id] - 1];',
    '}',
    '}',
])
generated = '\n'.join(source) + '\n'
target = project / 'src' / 'catalog.cpp'
if args.check:
    assert target.read_text() == generated, f'{target} needs regeneration'
    header = (project / 'include/godfield/catalog.hpp').read_text()
    assert manifest['catalog_sha256'] in header, 'header fingerprint mismatch'
    print(f'Catalog verified: {len(rows)} cards, weight {manifest["total_selected_weight"]}.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
