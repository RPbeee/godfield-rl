"""Generate the strict Glory/Dark Cloud source allowlist, or verify with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
manifest = json.loads((directory / 'manifest.json').read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count']
assert [int(r['id']) for r in rows] == manifest['selection']['ids']
assert len({int(r['id']) for r in rows}) == len(rows)
assert dict(Counter(r['kind'] for r in rows)) == manifest['counts_by_kind']
assert dict(Counter(r['harm'] for r in rows)) == manifest['counts_by_harm']
assert sum(r['harm'] == 'glory' for r in rows) == manifest['glory_source_count']
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight']
for original in ('legacy-neutral-v1','legacy-miracles-v1','legacy-elements-v1','legacy-chance-v1','legacy-reflection-v1','legacy-disease-v1'):
    old_ids = {int(r['id']) for r in csv.DictReader((directory.parent / original / 'catalog.csv').read_text().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable','harm','on_defense'])
element_map = {'':'neutral','FIRE':'fire','WATER':'water','TREE':'wood','SOIL':'stone'}
for row in source_rows:
    assert row['type'] == 'WEAPON' and row['attack_kind'] == 'ATK'
    assert row['attack_extra'] in ('GLORY','DARK_CLOUD')
    assert row['attribute'] in element_map
    assert row['defense_extra'] == '' and row['defense_kind'] in ('','DFS')
    assert int(row['hit_rate'] or 0) == 0 and int(row['weight']) > 0
    defense = int(row['sub_value'] or 0) if row['defense_kind'] == 'DFS' else 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'weapon', element_map[row['attribute']],
                     int(row['value']), 0, defense, 0, 0, int(row['price']), int(row['weight']),
                     0, row['attack_extra'].lower(), 0])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-harms-v1/generate.py.',
    '// Source rows, exclusions and retrieval limits: data/legacy-harms-v1/manifest.json.',
    '#include "godfield/harms.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<HarmCard, harm_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}}, Element::{row["element"]}, Harm::{row["harm"]}, {"true" if int(row["on_defense"]) else "false"}}},')
lines += [
    '}};',
    'static_assert(records.size() == 1 && records[0].card.id == 43);',
    'static_assert(records[0].harm == Harm::dark_cloud && !records[0].on_defense);',
    '}',
    'std::span<const HarmCard> harm_catalog() noexcept { return records; }',
    'const HarmCard* find_harm_card(CardId id) noexcept {',
    '    switch (id) {',
]
for i, row in enumerate(rows):
    lines.append(f'    case {int(row["id"])}: return &records[{i}];')
lines += ['    default: return nullptr;', '    }', '}', '}']
generated = '\n'.join(lines) + '\n'
target = project / 'src/harms.cpp'
if args.check:
    assert target.read_text() == generated, 'harms.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/harms.hpp').read_text()
    print(f'Harm catalog verified: {len(rows)} source record, no ordinary Glory source.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
