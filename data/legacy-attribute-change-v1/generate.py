"""Generate the two historical attribute setters, or verify them with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 2
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [65, 85]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 2
assert len(manifest['previous_catalog_sha256']) == 10
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable'])
for row in source_rows:
    assert row['type'] == 'WEAPON' and row['attack_kind'] == 'ATK'
    assert row['attack_extra'] == 'ADD_ATTRIBUTE'
    assert row['defense_kind'] == row['defense_extra'] == row['sub_value'] == row['hit_rate'] == ''
    assert row['attribute'] in ('FIRE', 'WATER')
    assert int(row['weight']) > 0
    # ADD_ATTRIBUTE is not INCREASE_ATK: getAtk() is used as the initial
    # damage only when no preceding weapon has established that damage.
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'weapon',
                     row['attribute'].lower(), int(row['value']), 0, 0, 0, 0,
                     int(row['price']), int(row['weight']), 0])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-attribute-change-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-attribute-change-v1/manifest.json.',
    '#include "godfield/attribute_change.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<AttributeChangeCard, attribute_change_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, false}}, Element::{row["element"]}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.kind != Kind::weapon || card.attack <= 0',
    '            || card.boost != 0 || card.defense != 0 || card.hp != 0 || card.mp != 0',
    '            || card.price < 0 || card.weight <= 0 || card.discardable',
    '            || (entry.element != Element::fire && entry.element != Element::water)) return false;',
    '        previous = card.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    'constexpr std::array<std::uint8_t, 86> make_index() {',
    '    std::array<std::uint8_t, 86> index{};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const AttributeChangeCard> attribute_change_catalog() noexcept { return records; }',
    'const AttributeChangeCard* find_attribute_change_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/attribute_change.cpp'
if args.check:
    assert target.read_text() == generated, 'attribute_change.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/attribute_change.hpp').read_text()
    print('Attribute-change catalog verified: 2 setters; ten older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
