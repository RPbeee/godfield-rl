"""Generate src/miracles.cpp from the separately versioned two-miracle pool."""
from pathlib import Path
import argparse
import csv
import hashlib
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
raw = (directory / "catalog.csv").read_bytes()
manifest = json.loads((directory / "manifest.json").read_text())
assert hashlib.sha256(raw).hexdigest() == manifest["catalog_sha256"]
rows = list(csv.DictReader(raw.decode().splitlines()))
assert len(rows) == manifest["catalog_count"] == 2
assert [int(r["id"]) for r in rows] == manifest["selection"]["ids"]
assert sum(int(r["weight"]) for r in rows) == manifest["total_selected_weight"]
assert all(manifest['stable_slots'][r['id']] == i for i, r in enumerate(rows))

lines = [
    '// Generated by data/legacy-miracles-v1/generate.py.',
    '// Historical facts and provenance: data/legacy-miracles-v1/manifest.json.',
    '#include "godfield/miracles.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<Miracle, miracle_count> records{{',
]
for row in rows:
    assert row['effect'] in ('heal', 'money')
    numeric = ', '.join(str(int(row[field])) for field in ('amount','cost','weight'))
    lines.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, MiracleEffect::{row["effect"]}, {numeric}}},')
lines += [
    '}};',
    'static_assert(records[0].id == 216 && records[1].id == 220);',
    '}',
    'std::span<const Miracle> miracles() noexcept { return records; }',
    'int miracle_index(CardId id) noexcept {',
    '    switch (id) {',
]
for i, row in enumerate(rows):
    lines.append(f'    case {int(row["id"])}: return {i};')
lines += [
    '    default: return -1;',
    '    }',
    '}',
    'const Miracle* find_miracle(CardId id) noexcept {',
    '    const int slot = miracle_index(id);',
    '    return slot < 0 ? nullptr : &records[slot];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/miracles.cpp'
if args.check:
    assert target.read_text() == generated, 'miracles.cpp needs regeneration'
    header = (project / 'include/godfield/miracles.hpp').read_text()
    assert manifest['catalog_sha256'] in header, 'header fingerprint mismatch'
    print('Miracle catalog verified: two stable slots, total weight 2.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
