"""Generate physical SUNDRY boost238, or verify with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source) == manifest['catalog_count'] == 1
assert [int(r['id']) for r in rows] == manifest['selection']['ids'] == [238]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight'] == 2
assert manifest['stable_local_slots'] == {'238':0}
assert len(manifest['previous_catalog_sha256']) == 34
old_ids = set()
for original, expected in manifest['previous_catalog_sha256'].items():
    raw = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(raw).hexdigest() == expected == old_manifest['catalog_sha256']
    seen = {int(r['id']) for r in csv.DictReader(raw.decode().splitlines())}
    assert 238 not in seen and not seen & old_ids, 'catalog ID collision'
    old_ids |= seen
assert len(old_ids) == 224
prices = (directory.parent / 'legacy-selling-v1/sale-prices.csv').read_bytes()
selling = json.loads((directory.parent / 'legacy-selling-v1/manifest.json').read_text())
assert hashlib.sha256(prices).hexdigest() == manifest['previous_sale_prices_sha256'] == selling['sale_prices_sha256']
assert 238 not in {int(r['id']) for r in csv.DictReader(prices.decode().splitlines())}
row = source[0]
assert (row['id'],row['type'],row['attack_extra'],row['sub_value'],row['price'],row['weight']) == ('238','SUNDRY','INCREASE_ATK','10','15','2')
for field in ('attack_kind','defense_kind','defense_extra','attribute','value','hit_rate'): assert row[field] == ''
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
writer.writerow([238,'legacy-238','sundry',0,10,0,0,0,15,2,1])
assert normalized.getvalue().encode() == catalog_bytes
header = (project / 'include/godfield/sundry_boost.hpp').read_text()
assert manifest['catalog_sha256'] in header
generated = '// Generated by data/legacy-sundry-boost-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-sundry-boost-v1/manifest.json.\n#include "godfield/sundry_boost.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<SundryBoostCard, sundry_boost_card_count> records{{\n    {{238, "legacy-238", Kind::sundry, 0, 10, 0, 0, 0, 15, 2, true}},\n}};\nstatic_assert(records[0].card.id == 238 && records[0].card.kind == Kind::sundry\n    && records[0].card.attack == 0 && records[0].card.boost == 10 && records[0].card.defense == 0);\n}\nstd::span<const SundryBoostCard> sundry_boost_catalog() noexcept { return records; }\nint sundry_boost_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }\nconst SundryBoostCard* find_sundry_boost_card(CardId id) noexcept {\n    return sundry_boost_index(id) < 0 ? nullptr : &records[0];\n}\n}\n'
path = project / 'src/sundry_boost.cpp'
if args.check:
    assert path.read_text() == generated, 'sundry_boost.cpp needs regeneration'
    print('SUNDRY boost verified: one artifact; thirty-four old catalogs and216 prices intact.')
else:
    path.write_text(generated)
    print(f'Generated {path}.')
