"""Generate the historical attribute-removal armor, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [195]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 3
assert len(manifest['previous_catalog_sha256']) == 11
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable'])
for row in source_rows:
    assert row['type'] == 'PROTECTOR' and row['defense_extra'] == 'REMOVE_ATTRIBUTE'
    for field in ('attack_kind','attack_extra','defense_kind','attribute','value','sub_value','hit_rate'):
        assert row[field] == ''
    assert int(row['weight']) > 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'armor',
                     0, 0, 0, 0, 0, int(row['price']), int(row['weight']), 1])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-attribute-removal-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-attribute-removal-v1/manifest.json.',
    '#include "godfield/attribute_removal.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<AttributeRemovalCard, attribute_removal_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, true}}}},')
lines += [
    '}};',
    'static_assert(records[0].card.id == 195 && records[0].card.kind == Kind::armor',
    '    && records[0].card.attack == 0 && records[0].card.boost == 0',
    '    && records[0].card.defense == 0 && records[0].card.hp == 0 && records[0].card.mp == 0',
    '    && records[0].card.price == 15 && records[0].card.weight == 3 && records[0].card.discardable);',
    '}',
    'std::span<const AttributeRemovalCard> attribute_removal_catalog() noexcept { return records; }',
    'const AttributeRemovalCard* find_attribute_removal_card(CardId id) noexcept {',
    '    return id == records[0].card.id ? &records[0] : nullptr;',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/attribute_removal.cpp'
if args.check:
    assert target.read_text() == generated, 'attribute_removal.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/attribute_removal.hpp').read_text()
    print('Attribute-removal catalog verified: one complete effect; eleven older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
