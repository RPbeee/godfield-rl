"""Generate both complete additive miracles, or verify them with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 2
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [197,217]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 2
assert manifest['stable_local_slots'] == {'197':0,'217':1}
assert len(manifest['previous_catalog_sha256']) == 19
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','element','amount','cost','weight'])
for row in source_rows:
    assert row['type'] == 'MAGIC' and row['attack_kind'] == 'ATK' and row['attack_extra'] == 'INCREASE_ATK'
    for field in ('defense_kind','defense_extra','hit_rate'):
        assert row[field] == ''
    if int(row['id']) == 197:
        assert (row['attribute'],row['value'],row['sub_value'],row['price']) == ('FIRE','2','2','10')
    else:
        assert int(row['id']) == 217
        assert (row['attribute'],row['value'],row['sub_value'],row['price']) == ('LIGHT','10','7','15')
    assert int(row['weight']) > 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', row['attribute'].lower(),
                     int(row['value']), int(row['sub_value']), int(row['weight'])])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-additive-miracles-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-additive-miracles-v1/manifest.json.',
    '#include "godfield/additive_miracles.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<AdditiveMiracle, additive_miracle_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('amount','cost','weight'))
    lines.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, Element::{row["element"]}, {fields}}},')
lines += [
    '}};',
    'static_assert(records[0].id == 197 && records[0].element == Element::fire',
    '    && records[0].amount == 2 && records[0].cost == 2 && records[0].weight == 1',
    '    && records[1].id == 217 && records[1].element == Element::light',
    '    && records[1].amount == 10 && records[1].cost == 7 && records[1].weight == 1);',
    '}',
    'std::span<const AdditiveMiracle> additive_miracles() noexcept { return records; }',
    'int additive_miracle_index(CardId id) noexcept {',
    '    if (id == records[0].id) return 0;',
    '    if (id == records[1].id) return 1;',
    '    return -1;',
    '}',
    'const AdditiveMiracle* find_additive_miracle(CardId id) noexcept {',
    '    const auto index = additive_miracle_index(id);',
    '    return index < 0 ? nullptr : &records[index];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/additive_miracles.cpp'
if args.check:
    assert target.read_text() == generated, 'additive_miracles.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/additive_miracles.hpp').read_text()
    print('Additive miracles verified: two complete dual-role spells; nineteen older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
