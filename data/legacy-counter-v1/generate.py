"""Generate the single historical Stone counter, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [190]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 1
assert manifest['counter_multiplier'] == 2
assert len(manifest['previous_catalog_sha256']) == 12
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable','multiplier'])
for row in source_rows:
    assert row['type'] == 'PROTECTOR' and row['attack_kind'] == 'ATK'
    assert row['defense_kind'] == 'COUNTER' and row['attribute'] == 'SOIL'
    for field in ('attack_extra','defense_extra','value','sub_value','hit_rate'):
        assert row[field] == ''
    assert int(row['weight']) > 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'armor', 'stone',
                     0, 0, 0, 0, 0, int(row['price']), int(row['weight']), 1,
                     manifest['counter_multiplier']])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-counter-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-counter-v1/manifest.json.',
    '#include "godfield/counter.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<CounterCard, counter_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, true}}, Element::{row["element"]}, {int(row["multiplier"])}}},')
lines += [
    '}};',
    'static_assert(records[0].card.id == 190 && records[0].card.kind == Kind::armor',
    '    && records[0].card.attack == 0 && records[0].card.boost == 0',
    '    && records[0].card.defense == 0 && records[0].card.hp == 0 && records[0].card.mp == 0',
    '    && records[0].card.price == 10 && records[0].card.weight == 1 && records[0].card.discardable',
    '    && records[0].element == Element::stone && records[0].multiplier == 2);',
    '}',
    'std::span<const CounterCard> counter_catalog() noexcept { return records; }',
    'const CounterCard* find_counter_card(CardId id) noexcept {',
    '    return id == records[0].card.id ? &records[0] : nullptr;',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/counter.cpp'
if args.check:
    assert target.read_text() == generated, 'counter.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/counter.hpp').read_text()
    print('Counter catalog verified: one complete Stone counter; twelve older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
