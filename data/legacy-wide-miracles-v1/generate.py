"""Generate the complete wide miracle, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [209]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 1
assert manifest['stable_local_slots'] == {'209':0}
assert len(manifest['previous_catalog_sha256']) == 21
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','element','cost','weight','hit_rate'])
for row in source_rows:
    assert row['id'] == '209' and row['type'] == 'MAGIC' and row['attack_extra'] == 'WIDE_ATK'
    for field in ('attack_kind','defense_kind','defense_extra','attribute','value'):
        assert row[field] == ''
    assert (row['sub_value'], row['price'], row['weight'], row['hit_rate']) == ('5','10','1','100')
    writer.writerow([209, 'legacy-209', 'neutral', 5, 1, 100])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-wide-miracles-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-wide-miracles-v1/manifest.json.',
    '#include "godfield/wide_miracles.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<WideMiracle, wide_miracle_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('cost','weight','hit_rate'))
    lines.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, Element::{row["element"]}, {fields}}},')
lines += [
    '}};',
    'static_assert(records[0].id == 209 && records[0].element == Element::neutral',
    '    && records[0].cost == 5 && records[0].weight == 1 && records[0].hit_rate == 100);',
    '}',
    'std::span<const WideMiracle> wide_miracles() noexcept { return records; }',
    'int wide_miracle_index(CardId id) noexcept {',
    '    if (id == records[0].id) return 0;',
    '    return -1;',
    '}',
    'const WideMiracle* find_wide_miracle(CardId id) noexcept {',
    '    const auto index = wide_miracle_index(id);',
    '    return index < 0 ? nullptr : &records[index];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/wide_miracles.cpp'
if args.check:
    assert target.read_text() == generated, 'wide_miracles.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/wide_miracles.hpp').read_text()
    print('Wide miracle verified: one complete added-only spell; twenty-one older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
