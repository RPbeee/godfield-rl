"""Generate all complete ABSORB_HP rows, or verify them with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json
import re

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
ids = [26,42,103,221]
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 4
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == ids
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 4
assert manifest['stable_local_slots'] == {'weapons':{'26':0,'42':1,'103':2},'miracles':{'221':0}}
assert len(manifest['previous_catalog_sha256']) == 27
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not set(ids).intersection(old_ids), 'catalog ID collision'
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','source_kind','element','amount','cost','hit_rate','price','weight'])
expected = {26:('WEAPON','',7,0,0,10),42:('WEAPON','',11,0,0,15),103:('WEAPON','TREE',3,0,75,10),221:('MAGIC','LIGHT',10,10,0,15)}
for row in source_rows:
    id = int(row['id'])
    kind, attribute, amount, cost, rate, price = expected[id]
    assert (row['type'],row['attack_kind'],row['attack_extra'],row['attribute']) == (kind,'ATK','ABSORB_HP',attribute)
    assert row['defense_kind'] == row['defense_extra'] == ''
    assert (row['value'],row['sub_value'],row['hit_rate'],row['price'],row['weight']) == (str(amount),str(cost) if cost else '',str(rate) if rate else '',str(price),'1')
    element = {'':'neutral','TREE':'wood','LIGHT':'light'}[attribute]
    writer.writerow([id,f'legacy-{id:03}',kind.lower(),element,amount,cost,rate,price,1])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/hp_absorption.hpp').read_text()
new_ids = [197,198,199,200,203,204,205,206,207,209,210,214,215,216,217,218,219,220,221,222,223,226]
rank = re.search(r'hp_absorption_retained_type_ids\s*\{([^}]+)\}',header).group(1)
assert [int(x) for x in re.findall(r'\d+',rank)] == manifest['hp_absorption_retained_type_ids'] == new_ids
old_header = (project / 'include/godfield/forgetting.hpp').read_text()
old_rank = re.search(r'retained_type_ids\s*\{([^}]+)\}',old_header).group(1)
assert [int(x) for x in re.findall(r'\d+',old_rank)] == [id for id in new_ids if id != 221]
lines = [
    '// Generated by data/legacy-hp-absorption-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-hp-absorption-v1/manifest.json.',
    '#include "godfield/hp_absorption.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<HPAbsorptionCard, hp_absorption_card_count> weapons{{',
]
for row in rows:
    if row['source_kind'] != 'weapon': continue
    lines.append(f'    {{{{{row["id"]}, {json.dumps(row["label"])}, Kind::weapon, {row["amount"]}, 0, 0, 0, 0, {row["price"]}, {row["weight"]}, false}}, Element::{row["element"]}, {row["hit_rate"]}}},')
lines += [
    '}};',
    'constexpr std::array<HPAbsorptionMiracle, hp_absorption_miracle_count> spells{{',
    '    {221, "legacy-221", Element::light, 10, 10, 1},',
    '}};',
    'static_assert(weapons[0].card.id == 26 && weapons[1].card.id == 42 && weapons[2].card.id == 103);',
    'static_assert(spells[0].id == 221 && spells[0].amount == 10 && spells[0].cost == 10);',
    '}',
    'std::span<const HPAbsorptionCard> hp_absorption_catalog() noexcept { return weapons; }',
    'int hp_absorption_index(CardId id) noexcept {',
    '    for (int i = 0; i < hp_absorption_card_count; ++i) if (weapons[i].card.id == id) return i;',
    '    return -1;',
    '}',
    'const HPAbsorptionCard* find_hp_absorption_card(CardId id) noexcept {',
    '    const auto index = hp_absorption_index(id);',
    '    return index < 0 ? nullptr : &weapons[index];',
    '}',
    'std::span<const HPAbsorptionMiracle> hp_absorption_miracles() noexcept { return spells; }',
    'int hp_absorption_miracle_index(CardId id) noexcept { return id == spells[0].id ? 0 : -1; }',
    'const HPAbsorptionMiracle* find_hp_absorption_miracle(CardId id) noexcept {',
    '    return hp_absorption_miracle_index(id) < 0 ? nullptr : &spells[0];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/hp_absorption.cpp'
if args.check:
    assert target.read_text() == generated, 'hp_absorption.cpp needs regeneration'
    assert manifest['catalog_sha256'] in header
    print('HP absorption verified: three weapons/one spell; old27catalogs and21-ID order intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
