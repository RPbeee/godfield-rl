"""Generate four complete counter extensions, or verify them with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 4
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [187, 191, 192, 193]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 4
assert dict(Counter(row['effect'] for row in rows)) == manifest['counts_by_effect']
assert len(manifest['previous_catalog_sha256']) == 13
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable','effect','multiplier','hit_rate','harm','target'])
for row in source_rows:
    assert row['type'] == 'PROTECTOR' and row['defense_kind'] == 'COUNTER'
    for field in ('defense_extra','value','sub_value'):
        assert row[field] == ''
    assert int(row['weight']) > 0
    identity = (row['attack_kind'], row['attack_extra'], row['attribute'], int(row['hit_rate'] or 0))
    if int(row['id']) == 187:
        assert identity == ('ATK', '', 'FIRE', 75)
        effect, multiplier, harm, target = 'damage', 1, 'none', 'all_enemies'
    elif int(row['id']) == 191:
        assert identity == ('ADD_HARM', 'GLORY', 'LIGHT', 0)
        effect, multiplier, harm, target = 'harm', 0, 'glory', 'incoming_source'
    elif int(row['id']) == 192:
        assert identity == ('ADD_HARM', 'DARK_CLOUD', 'DARK', 0)
        effect, multiplier, harm, target = 'harm', 0, 'dark_cloud', 'incoming_source'
    else:
        assert int(row['id']) == 193 and identity == ('INCREASE_MP', '', '', 0)
        effect, multiplier, harm, target = 'mana', 2, 'none', 'self'
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'armor',
                     row['attribute'].lower() if row['attribute'] else 'neutral',
                     0, 0, 0, 0, 0, int(row['price']), int(row['weight']), 1,
                     effect, multiplier, int(row['hit_rate'] or 0), harm, target])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-counter-extensions-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-counter-extensions-v1/manifest.json.',
    '#include "godfield/counter_extensions.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<CounterExtensionCard, counter_extension_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, true}}, Element::{row["element"]}, CounterExtensionEffect::{row["effect"]}, {int(row["multiplier"])}, {int(row["hit_rate"])}, Harm::{row["harm"]}, CounterExtensionTarget::{row["target"]}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.kind != Kind::armor || card.attack != 0 || card.boost != 0',
    '            || card.defense != 0 || card.hp != 0 || card.mp != 0 || card.price != 10',
    '            || card.weight != 1 || !card.discardable) return false;',
    '        previous = card.id;',
    '    }',
    '    return records[0].card.id == 187 && records[0].multiplier == 1 && records[0].hit_rate == 75',
    '        && records[1].card.id == 191 && records[1].harm == Harm::glory',
    '        && records[2].card.id == 192 && records[2].harm == Harm::dark_cloud',
    '        && records[3].card.id == 193 && records[3].element == Element::neutral',
    '        && records[3].multiplier == 2 && records[3].target == CounterExtensionTarget::self;',
    '}',
    'static_assert(valid_catalog());',
    'constexpr std::array<std::uint8_t, 194> make_index() {',
    '    std::array<std::uint8_t, 194> index{};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const CounterExtensionCard> counter_extensions_catalog() noexcept { return records; }',
    'const CounterExtensionCard* find_counter_extension_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/counter_extensions.cpp'
if args.check:
    assert target.read_text() == generated, 'counter_extensions.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/counter_extensions.hpp').read_text()
    print('Counter extensions verified: four complete effects; thirteen older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
