"""Generate eight complete historical magic blockers, or verify with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 8
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [27,54,55,152,165,182,183,185]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 8
assert dict(Counter(row['kind'] for row in rows)) == manifest['counts_by_kind']
assert manifest['mandatory_special_when_magic'] and manifest['mp_cost'] == 0
assert len(manifest['previous_catalog_sha256']) == 18
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(row['id']) for row in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable'])
for row in source_rows:
    assert row['type'] in ('WEAPON', 'PROTECTOR') and row['defense_extra'] == 'BLOCK_MAGIC'
    for field in ('attribute','sub_value','hit_rate'):
        assert row[field] == ''
    assert row['attack_extra'] in ('', 'INCREASE_ATK') and int(row['weight']) > 0
    weapon = row['type'] == 'WEAPON'
    assert row['attack_kind'] == ('ATK' if weapon else '')
    assert row['defense_kind'] == ('' if weapon else 'DFS')
    assert row['attack_extra'] == ('INCREASE_ATK' if int(row['id']) == 55 else '')
    value = int(row['value'])
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', 'weapon' if weapon else 'armor',
                     'neutral', value if weapon else 0, value if row['attack_extra'] == 'INCREASE_ATK' else 0,
                     0 if weapon else value, 0, 0, int(row['price']), int(row['weight']), int(not weapon)])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-magic-block-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-magic-block-v1/manifest.json.',
    '#include "godfield/magic_block.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<MagicBlockCard, magic_block_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.attack < 0 || card.defense < 0 || card.hp != 0 || card.mp != 0',
    '            || card.price < 0 || card.weight != 1 || card.boost != (card.id == 55 ? 15 : 0)',
    '            || (card.kind != Kind::weapon && card.kind != Kind::armor)',
    '            || card.discardable == (card.kind == Kind::weapon)) return false;',
    '        previous = card.id;',
    '    }',
    '    return records[0].card.id == 27 && records[0].card.attack == 7',
    '        && records[1].card.id == 54 && records[1].card.attack == 15',
    '        && records[2].card.id == 55 && records[2].card.attack == 15',
    '        && records[3].card.id == 152 && records[3].card.defense == 6',
    '        && records[4].card.id == 165 && records[4].card.defense == 8',
    '        && records[5].card.id == 182 && records[5].card.defense == 13',
    '        && records[6].card.id == 183 && records[6].card.defense == 14',
    '        && records[7].card.id == 185 && records[7].card.defense == 15;',
    '}',
    'static_assert(valid_catalog());',
    'constexpr std::array<std::uint8_t, 186> make_index() {',
    '    std::array<std::uint8_t, 186> index{};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const MagicBlockCard> magic_block_catalog() noexcept { return records; }',
    'const MagicBlockCard* find_magic_block_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/magic_block.cpp'
if args.check:
    assert target.read_text() == generated, 'magic_block.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/magic_block.hpp').read_text()
    print('Magic blockers verified: eight complete dual-role artifacts; eighteen older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
