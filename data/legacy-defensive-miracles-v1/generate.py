"""Generate the separate defensive miracle group, or verify with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
manifest = json.loads((directory / 'manifest.json').read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count']
assert [int(r['id']) for r in rows] == manifest['selection']['ids']
assert len({int(r['id']) for r in rows}) == len(rows)
assert dict(Counter(r['kind'] for r in rows)) == manifest['counts_by_kind']
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight']
assert manifest['storage_group'] == 'defensive_abilities'
for i,row in enumerate(rows):
    assert int(row['kind_index']) == manifest['stable_kind_slots'][row['id']] == i
for original in ('legacy-neutral-v1','legacy-miracles-v1','legacy-elements-v1','legacy-chance-v1',
                 'legacy-reflection-v1','legacy-disease-v1','legacy-harms-v1','legacy-celestial-v1',
                 'legacy-offensive-miracles-v1'):
    old_path = directory.parent / original
    old_bytes = (old_path / 'catalog.csv').read_bytes()
    old_manifest = json.loads((old_path / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == old_manifest['catalog_sha256']
    old_ids = {int(r['id']) for r in csv.DictReader(old_bytes.decode().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','cost','weight','kind_index'])
mapping = {'FLICK_MAGIC':'bounce_magic','BLOCK_WEAPON':'block_weapon'}
for index,row in enumerate(source_rows):
    assert row['type'] == 'MAGIC'
    assert row['attack_kind'] == row['attack_extra'] == row['defense_kind'] == row['attribute'] == ''
    assert row['defense_extra'] in mapping
    assert int(row['value'] or 0) == int(row['hit_rate'] or 0) == 0
    assert int(row['sub_value']) > 0 and int(row['weight']) > 0 and int(row['price']) > 0
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', mapping[row['defense_extra']],
                     int(row['sub_value']), int(row['weight']), index])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-defensive-miracles-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-defensive-miracles-v1/manifest.json.',
    '#include "godfield/defensive_miracles.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<DefensiveMiracle, defensive_miracle_count> records{{',
]
for row in rows:
    lines.append(f'    {{{int(row["id"])}, {json.dumps(row["label"])}, DefensiveMiracleKind::{row["kind"]}, {int(row["cost"])}, {int(row["weight"])}}},')
lines += [
    '}};',
    'static_assert(records[0].id == 210 && records[1].id == 215);',
    'static_assert(records[0].cost == 5 && records[1].cost == 6);',
    '}',
    'std::span<const DefensiveMiracle> defensive_miracles() noexcept { return records; }',
    'int defensive_miracle_index(CardId id) noexcept {',
    '    switch (id) {',
]
for i,row in enumerate(rows):
    lines.append(f'    case {int(row["id"])}: return {i};')
lines += [
    '    default: return -1;',
    '    }',
    '}',
    'const DefensiveMiracle* find_defensive_miracle(CardId id) noexcept {',
    '    const int slot = defensive_miracle_index(id);',
    '    return slot < 0 ? nullptr : &records[slot];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/defensive_miracles.cpp'
if args.check:
    assert target.read_text() == generated, 'defensive_miracles.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/defensive_miracles.hpp').read_text()
    print(f'Defensive miracle catalog verified: {len(rows)} separate slots; nine older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
