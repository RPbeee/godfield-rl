"""Generate the official fact catalog, or verify without network using --check."""
from pathlib import Path
import argparse, collections, hashlib, json, re, subprocess, sys
p=Path(__file__).resolve().parent
project=p.parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
m=json.loads((p/'manifest.json').read_text()); raw=(p/'cards.json').read_bytes();rows=json.loads(raw)
h=lambda b:hashlib.sha256(b).hexdigest()
assert h(raw)==m['cards_sha256'] and len(rows)==m['catalog_count']==296
assert [r['id']for r in rows]==list(range(1,297))
assert dict(collections.Counter(r['category']for r in rows))==m['category_counts']
assert sum(r.get('giftRate',0)for r in rows)==m['total_gift_rate']
assert len({r['imageName']for r in rows})==296
allowed={'id','name','imageName','category','element','atk','isPlusAtk','hitRate','def','ability','abilityValue','curse','guardian','price','cost','giftRate','appearanceRate','guardianAttackRate'}
numerics=['atk','hitRate','def','abilityValue','price','cost','giftRate','appearanceRate','guardianAttackRate']
for r in rows:
 assert not set(r)-allowed
 assert all(type(r[k])is int and r[k]>=0 for k in numerics if k in r)
 assert r.get('isPlusAtk',True) is True
 assert r['category'] in m['enums']['Category']
 for field,typ in [('element','Element'),('curse','Curse'),('guardian','Guardian'),('ability','Ability')]:
  if field in r:assert r[field] in m['enums'][typ]
for name,digest in m['previous_legacy_catalog_sha256'].items():
 assert h((p.parent/name/'catalog.csv').read_bytes())==digest
assert len(m['previous_legacy_catalog_sha256'])==37
assert h((p.parent/'legacy-selling-v1/sale-prices.csv').read_bytes())==m['previous_legacy_sale_prices_sha256']
assert m['cards_sha256'] in (project/'include/godfield/official_catalog.hpp').read_text()
def snake(x):return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',re.sub(r'([A-Z])([A-Z][a-z])',r'\1_\2',x)).lower()
def text(x):return json.dumps(x,ensure_ascii=False)
lines=['// Generated by data/official-v1/generate.py; factual public catalog only.','#include "godfield/official_catalog.hpp"','#include <array>','namespace godfield::official {','namespace {','constexpr std::array<Card, catalog_count> records{{']
for r in rows:
 fields=[str(r['id']),text(r['name']),text(r['imageName']),'Category::'+r['category'],('Element::'+r['element'])if 'element'in r else 'std::nullopt','true'if r.get('isPlusAtk')is not None else 'false',str(r.get('atk',0)),str(r.get('hitRate',0)),str(r.get('def',0)),'Ability::'+snake(r.get('ability','none')),str(r.get('abilityValue',0)),'Curse::'+r.get('curse','none'),'Guardian::'+r.get('guardian','none')]+[str(r.get(k,0))for k in ['price','cost','giftRate','appearanceRate','guardianAttackRate']]
 lines.append('    {'+', '.join(fields)+'},')
lines+=['}};','static_assert(records.front().id == 1 && records.back().id == catalog_count);','}','std::span<const Card> catalog() noexcept { return records; }','int card_index(CardId id) noexcept { return id >= 1 && id <= catalog_count ? static_cast<int>(id) - 1 : -1; }','const Card* find_card(CardId id) noexcept { const int i = card_index(id); return i < 0 ? nullptr : &records[i]; }']
for typ,values in m['enums'].items():
 fname=re.sub(r'([a-z])([A-Z])',r'\1_\2',typ).lower()+'_name'
 lines+=['std::string_view '+fname+'('+typ+' value) noexcept {','    switch (value) {']
 for v in values:lines.append('    case '+typ+'::'+snake(v)+': return '+text(''if v=='none'else v)+';')
 lines+=['    }','    return {};','}']
lines+=['}'];generated='\n'.join(lines)+'\n';path=project/'src/official_catalog.cpp'
if args.check:
 assert path.read_text()==generated,'official_catalog.cpp needs regeneration'
 print('Official296 facts verified; legacy37 catalog fingerprints unchanged.')
else:path.write_text(generated)

assert h((p/m["crosswalk_file"]).read_bytes())==m["crosswalk_sha256"]
subprocess.run([sys.executable,str(p/"crosswalk.py"),"--check"],check=True)
