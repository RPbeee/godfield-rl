"""Generate a source-preserving disease/cure allowlist, or verify with --check."""
from pathlib import Path
import argparse
from collections import Counter
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
manifest = json.loads((directory / 'manifest.json').read_text())
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count']
assert [int(r['id']) for r in rows] == manifest['selection']['ids']
assert len({int(r['id']) for r in rows}) == len(rows)
for column, key in [('kind','counts_by_kind'),('disease','counts_by_disease'),('cure','counts_by_cure')]:
    assert dict(Counter(r[column] for r in rows)) == manifest[key]
assert sum(int(r['weight']) for r in rows) == manifest['total_selected_weight']
assert sum(int(r['on_defense']) for r in rows) == manifest['defense_disease_count']
for original in ('legacy-neutral-v1','legacy-miracles-v1','legacy-elements-v1','legacy-chance-v1','legacy-reflection-v1'):
    old_ids = {int(r['id']) for r in csv.DictReader((directory.parent / original / 'catalog.csv').read_text().splitlines())}
    assert not old_ids.intersection(int(r['id']) for r in rows), 'catalog ID collision'

normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','element','attack','boost','defense','hp','mp','price','weight','discardable','disease','cure','on_defense'])
element_map = {'':'neutral','FIRE':'fire','WATER':'water','TREE':'wood','SOIL':'stone'}
diseases = ('COLD','FEVER','HELL','HEAVEN')
cures = {'REMOVE_LOWER_HARMS':'lower','REMOVE_ALL_HARMS':'all'}
for row in source_rows:
    assert row['type'] in ('WEAPON','PROTECTOR','SUNDRY')
    assert row['attribute'] in element_map
    assert int(row['hit_rate'] or 0) == 0 and int(row['weight']) > 0
    weapon, armor = row['type'] == 'WEAPON', row['type'] == 'PROTECTOR'
    if weapon:
        assert row['attack_kind'] == 'ATK' and row['attack_extra'] in diseases
        assert row['defense_kind'] == row['defense_extra'] == ''
        kind, disease, cure = 'weapon', row['attack_extra'].lower(), 'none'
    elif armor:
        assert row['attack_kind'] == row['attack_extra'] == ''
        assert row['defense_kind'] == 'DFS' and row['defense_extra'] in diseases
        kind, disease, cure = 'armor', row['defense_extra'].lower(), 'none'
    else:
        assert row['defense_kind'] == row['defense_extra'] == row['attribute'] == ''
        if row['attack_kind'] == 'INCREASE_MP':
            assert row['attack_extra'] in diseases
            kind, disease, cure = 'mana', row['attack_extra'].lower(), 'none'
        else:
            assert row['attack_kind'] in cures and row['attack_extra'] == ''
            kind, disease, cure = 'heal', 'none', cures[row['attack_kind']]
    value = int(row['value'] or 0)
    writer.writerow([int(row['id']), f'legacy-{int(row["id"]):03}', kind, element_map[row['attribute']],
                     value if weapon else 0, 0, value if armor else 0, 0, value if kind == 'mana' else 0,
                     int(row['price']), int(row['weight']), int(not weapon), disease, cure, int(armor)])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'

lines = [
    '// Generated by data/legacy-disease-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-disease-v1/manifest.json.',
    '#include "godfield/disease.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<DiseaseCard, disease_card_count> records{{',
]
for row in rows:
    fields = ', '.join(str(int(row[field])) for field in ('attack','boost','defense','hp','mp','price','weight'))
    lines.append(f'    {{{{{int(row["id"])}, {json.dumps(row["label"])}, Kind::{row["kind"]}, {fields}, {"true" if int(row["discardable"]) else "false"}}}, Element::{row["element"]}, Disease::{row["disease"]}, Cure::{row["cure"]}, {"true" if int(row["on_defense"]) else "false"}}},')
lines += [
    '}};',
    'constexpr bool valid_catalog() {',
    '    CardId previous = 0;',
    '    for (const auto& entry : records) {',
    '        const auto& card = entry.card;',
    '        if (card.id <= previous || card.weight <= 0 || card.attack < 0',
    '            || card.boost != 0 || card.defense < 0 || card.hp < 0 || card.mp < 0',
    '            || card.price < 0 || (entry.disease == Disease::none && entry.cure == Cure::none)',
    '            || card.discardable == (card.kind == Kind::weapon)) return false;',
    '        previous = card.id;',
    '    }',
    '    return true;',
    '}',
    'static_assert(valid_catalog());',
    f'constexpr std::array<std::uint8_t, {int(rows[-1]["id"])+1}> make_index() {{',
    f'    std::array<std::uint8_t, {int(rows[-1]["id"])+1}> index{{}};',
    '    for (std::size_t i = 0; i < records.size(); ++i)',
    '        index[records[i].card.id] = static_cast<std::uint8_t>(i + 1);',
    '    return index;',
    '}',
    'constexpr auto index = make_index();',
    '}',
    'std::span<const DiseaseCard> disease_catalog() noexcept { return records; }',
    'const DiseaseCard* find_disease_card(CardId id) noexcept {',
    '    if (id >= index.size() || index[id] == 0) return nullptr;',
    '    return &records[index[id] - 1];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/disease.cpp'
if args.check:
    assert target.read_text() == generated, 'disease.cpp needs regeneration'
    assert manifest['catalog_sha256'] in (project / 'include/godfield/disease.hpp').read_text()
    print(f'Disease catalog verified: {len(rows)} complete source effects match native table.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
