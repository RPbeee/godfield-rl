"""Generate the two positive-weight pestle/mortar artifacts, or verify with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 2
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [99,245]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 2
assert manifest['stable_local_slots'] == {'pestle': {'99':0}, 'mortar': {'245':0}}
assert len(manifest['previous_catalog_sha256']) == 29
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    assert not {99,245} & {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}, 'catalog ID collision'
a,b = source_rows
assert (a['id'],a['type'],a['attack_kind'],a['attack_extra'],a['attribute'],a['value'],a['price'],a['weight']) == ('99','WEAPON','ATK','PESTLE','LIGHT','30','5','1')
assert (b['id'],b['type'],b['attack_extra'],b['weight']) == ('245','SUNDRY','MORTAR','1')
for field in ('defense_kind','defense_extra','sub_value','hit_rate'):
    assert a[field] == b[field] == ''
for field in ('attack_kind','attribute','value','price'):
    assert b[field] == ''
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable','element','mortar_amount'])
writer.writerow([99,'legacy-099','weapon',30,0,0,0,0,5,1,0,'light',999])
writer.writerow([245,'legacy-245','sundry',0,0,0,0,0,0,1,0,'neutral',0])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/pestle_mortar.hpp').read_text()
generated = '// Generated by data/legacy-pestle-mortar-v1/generate.py.\n// Source rows and retrieval limits: data/legacy-pestle-mortar-v1/manifest.json.\n#include "godfield/pestle_mortar.hpp"\n#include <array>\n\nnamespace godfield::legacy {\nnamespace {\nconstexpr std::array<PestleCard, pestle_card_count> pestles{{\n    {{99, "legacy-099", Kind::weapon, 30, 0, 0, 0, 0, 5, 1, false}, Element::light, 999},\n}};\nconstexpr std::array<MortarCard, mortar_card_count> mortars{{\n    {{245, "legacy-245", Kind::sundry, 0, 0, 0, 0, 0, 0, 1, false}},\n}};\nstatic_assert(pestles[0].card.id == 99 && pestles[0].card.attack == 30 && pestles[0].mortar_amount == 999);\nstatic_assert(mortars[0].card.id == 245 && mortars[0].card.price == 0 && !mortars[0].card.discardable);\n}\nstd::span<const PestleCard> pestle_catalog() noexcept { return pestles; }\nint pestle_index(CardId id) noexcept { return id == pestles[0].card.id ? 0 : -1; }\nconst PestleCard* find_pestle_card(CardId id) noexcept {\n    return pestle_index(id) < 0 ? nullptr : &pestles[0];\n}\nstd::span<const MortarCard> mortar_catalog() noexcept { return mortars; }\nint mortar_index(CardId id) noexcept { return id == mortars[0].card.id ? 0 : -1; }\nconst MortarCard* find_mortar_card(CardId id) noexcept {\n    return mortar_index(id) < 0 ? nullptr : &mortars[0];\n}\n}\n'
assert manifest['catalog_sha256'] in header
assert 'struct PestleCard { Card card; Element element; int mortar_amount; };' in header
assert 'struct MortarCard { Card card; };' in header
target = project / 'src/pestle_mortar.cpp'
if args.check:
    assert target.read_text() == generated, 'pestle_mortar.cpp needs regeneration'
    print('Pestle/mortar verified: two complete artifacts; twenty-nine older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
