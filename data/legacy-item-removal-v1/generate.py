"""Generate the complete positive-weight item-removal artifact, or verify it with --check."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json

directory = Path(__file__).resolve().parent
project = directory.parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
manifest = json.loads((directory / 'manifest.json').read_text())
source_bytes = (directory / 'source-rows.csv').read_bytes()
catalog_bytes = (directory / 'catalog.csv').read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == manifest['source_rows_sha256']
assert hashlib.sha256(catalog_bytes).hexdigest() == manifest['catalog_sha256']
source_rows = list(csv.DictReader(source_bytes.decode().splitlines()))
rows = list(csv.DictReader(catalog_bytes.decode().splitlines()))
assert len(rows) == len(source_rows) == manifest['catalog_count'] == 1
assert [int(row['id']) for row in rows] == manifest['selection']['ids'] == [240]
assert sum(int(row['weight']) for row in rows) == manifest['total_selected_weight'] == 3
assert manifest['stable_local_slots'] == {'240':0}
assert len(manifest['previous_catalog_sha256']) == 26
for original, expected in manifest['previous_catalog_sha256'].items():
    old_bytes = (directory.parent / original / 'catalog.csv').read_bytes()
    old_manifest = json.loads((directory.parent / original / 'manifest.json').read_text())
    assert hashlib.sha256(old_bytes).hexdigest() == expected == old_manifest['catalog_sha256']
    old_ids = {int(row['id']) for row in csv.DictReader(old_bytes.decode().splitlines())}
    assert 240 not in old_ids, 'catalog ID collision'
row = source_rows[0]
assert row['id'] == '240' and row['type'] == 'SUNDRY' and row['attack_kind'] == 'REMOVE_ITEMS'
for field in ('attack_extra','defense_kind','defense_extra','attribute','sub_value','hit_rate'):
    assert row[field] == ''
assert (row['value'], row['price'], row['weight']) == ('1','10','3')
normalized = io.StringIO(newline='')
writer = csv.writer(normalized, lineterminator='\n')
writer.writerow(['id','label','kind','attack','boost','defense','hp','mp','price','weight','discardable','amount'])
writer.writerow([240,'legacy-240','sundry',0,0,0,0,0,10,3,1,1])
assert normalized.getvalue().encode() == catalog_bytes, 'normalization differs from pinned catalog'
header = (project / 'include/godfield/item_removal.hpp').read_text()
lines = [
    '// Generated by data/legacy-item-removal-v1/generate.py.',
    '// Source rows and retrieval limits: data/legacy-item-removal-v1/manifest.json.',
    '#include "godfield/item_removal.hpp"',
    '#include <array>',
    '',
    'namespace godfield::legacy {',
    'namespace {',
    'constexpr std::array<ItemRemovalCard, item_removal_card_count> records{{',
    '    {{240, "legacy-240", Kind::sundry, 0, 0, 0, 0, 0, 10, 3, true}, 1},',
    '}};',
    'static_assert(records[0].card.id == 240 && records[0].card.kind == Kind::sundry',
    '    && records[0].card.price == 10 && records[0].card.weight == 3 && records[0].amount == 1);',
    '}',
    'std::span<const ItemRemovalCard> item_removal_catalog() noexcept { return records; }',
    'int item_removal_index(CardId id) noexcept { return id == records[0].card.id ? 0 : -1; }',
    'const ItemRemovalCard* find_item_removal_card(CardId id) noexcept {',
    '    return item_removal_index(id) < 0 ? nullptr : &records[0];',
    '}',
    '}',
]
generated = '\n'.join(lines) + '\n'
target = project / 'src/item_removal.cpp'
if args.check:
    assert target.read_text() == generated, 'item_removal.cpp needs regeneration'
    assert manifest['catalog_sha256'] in header
    print('Item removal verified: one complete artifact; twenty-six older catalogs intact.')
else:
    target.write_text(generated)
    print(f'Generated {target}.')
